import React, { useState } from 'react';
import {
  CityItinerary,
  ItineraryDay,
  Activity,
  ActivityCategory,
  ActivityPeriod,
} from '../data/itineraries';
import { PackingListSection } from './PackingListSection';
import {
  Calendar,
  Clock,
  MapPin,
  CheckCircle2,
  Circle,
  Lightbulb,
  Copy,
  Check,
  Compass,
  Footprints,
  CreditCard,
  Train,
  SlidersHorizontal,
  ChevronRight,
  ExternalLink,
} from 'lucide-react';

interface ItineraryViewProps {
  itinerary: CityItinerary;
  completedActivities: Set<string>;
  onToggleActivity: (activityId: string) => void;
  onSwitchCity: (cityName: string) => void;
}

export const ItineraryView: React.FC<ItineraryViewProps> = ({
  itinerary,
  completedActivities,
  onToggleActivity,
  onSwitchCity,
}) => {
  const [activeDayTab, setActiveDayTab] = useState<number | 'all'>('all');
  const [selectedCategory, setSelectedCategory] = useState<ActivityCategory | 'All'>('All');
  const [copied, setCopied] = useState(false);

  // Filter activities
  const filterActivities = (activities: Activity[]) => {
    return activities.filter((act) => {
      if (selectedCategory !== 'All' && act.category !== selectedCategory) {
        return false;
      }
      return true;
    });
  };

  const daysToRender: ItineraryDay[] =
    activeDayTab === 'all'
      ? itinerary.days
      : itinerary.days.filter((d) => d.day === activeDayTab);

  const totalActivities = itinerary.days.reduce(
    (acc, day) => acc + day.activities.length,
    0
  );

  const completedInCity = itinerary.days.reduce(
    (acc, day) =>
      acc + day.activities.filter((act) => completedActivities.has(act.id)).length,
    0
  );

  const handleCopySummary = () => {
    const lines: string[] = [
      `3-DAY TRAVEL ITINERARY: ${itinerary.name.toUpperCase()}, ${itinerary.country.toUpperCase()}`,
      `"${itinerary.tagline}"`,
      `=============================================`,
      `Transit: ${itinerary.logistics.transit}`,
      `Best Season: ${itinerary.logistics.bestSeason}`,
      `Daily Budget: ${itinerary.logistics.budgetPerDay}`,
      `Insider Rule: ${itinerary.logistics.localTip}`,
      ``,
    ];

    itinerary.days.forEach((day) => {
      lines.push(`--- DAY ${day.day}: ${day.title.toUpperCase()} ---`);
      lines.push(`Theme: ${day.theme}`);
      lines.push(`Walking: ${day.walkingEstimate} | Neighborhoods: ${day.neighborhoods.join(', ')}`);
      lines.push(``);
      day.activities.forEach((act) => {
        lines.push(`• [${act.time}] ${act.title} (${act.neighborhood})`);
        lines.push(`  Category: ${act.category} | Duration: ${act.duration} | Cost: ${act.cost}`);
        lines.push(`  Details: ${act.description}`);
        lines.push(`  Insider Tip: ${act.insiderTip}`);
        lines.push(``);
      });
    });

    if (itinerary.packingList && itinerary.packingList.length > 0) {
      lines.push(`--- 5 MUST-PACK ITEMS FOR ${itinerary.name.toUpperCase()} ---`);
      itinerary.packingList.forEach((item, idx) => {
        lines.push(`${idx + 1}. ${item.item} [${item.category}]: ${item.reason}`);
      });
      lines.push(``);
    }

    lines.push(`Generated by Wander3 Travel Planner`);

    navigator.clipboard.writeText(lines.join('\n')).then(() => {
      setCopied(true);
      setTimeout(() => setCopied(false), 2400);
    });
  };

  const categories: Array<ActivityCategory | 'All'> = [
    'All',
    'Landmark',
    'Culinary',
    'Culture',
    'Scenic Walk',
    'Neighborhood',
    'Leisure',
  ];

  return (
    <div className="max-w-6xl mx-auto px-4 sm:px-6 lg:px-8 py-10 space-y-10">
      {/* City Hero Card */}
      <section className="relative rounded-2xl overflow-hidden bg-neutral-900 text-white shadow-xl border border-neutral-200">
        <div className="relative h-72 sm:h-80 md:h-96 w-full overflow-hidden">
          <img
            src={itinerary.coverImage}
            alt={`${itinerary.name} cityscape`}
            className="w-full h-full object-cover object-center"
            referrerPolicy="no-referrer"
          />
          <div className="absolute inset-0 bg-gradient-to-t from-neutral-950 via-neutral-950/60 to-neutral-950/20" />

          {/* City Content Overlay */}
          <div className="absolute inset-0 p-6 sm:p-8 md:p-10 flex flex-col justify-end">
            <div className="flex items-center gap-2 text-xs text-neutral-300 font-medium mb-2">
              <span className="uppercase tracking-widest">{itinerary.country}</span>
              <span aria-hidden="true">·</span>
              <span>72-Hour Detailed Plan</span>
              <span aria-hidden="true">·</span>
              <span className="font-mono tabular-nums">{totalActivities} Curated Stops</span>
            </div>

            <h2 className="font-display text-3xl sm:text-4xl md:text-5xl font-extrabold tracking-tight text-white mb-2">
              {itinerary.name}
            </h2>

            <p className="text-neutral-200 text-sm sm:text-base max-w-3xl mb-4 text-balance">
              {itinerary.tagline}
            </p>

            <div className="flex flex-wrap items-center gap-3 pt-2 border-t border-white/20">
              <button
                onClick={handleCopySummary}
                className="inline-flex items-center gap-1.5 px-3.5 py-1.5 text-xs font-medium rounded-lg bg-white/10 hover:bg-white/20 text-white backdrop-blur-sm transition-colors border border-white/20"
              >
                {copied ? (
                  <>
                    <Check className="w-3.5 h-3.5 text-emerald-400" />
                    <span>Copied Itinerary</span>
                  </>
                ) : (
                  <>
                    <Copy className="w-3.5 h-3.5" />
                    <span>Copy Itinerary Text</span>
                  </>
                )}
              </button>

              <div className="text-xs text-neutral-300 ml-auto flex items-center gap-2">
                <span>Progress:</span>
                <span className="font-mono tabular-nums font-semibold text-white">
                  {completedInCity}/{totalActivities} stops
                </span>
                <div className="w-20 bg-white/20 rounded-full h-2 overflow-hidden">
                  <div
                    className="bg-emerald-400 h-full transition-all duration-300"
                    style={{
                      width: `${(completedInCity / totalActivities) * 100}%`,
                    }}
                  />
                </div>
              </div>
            </div>
          </div>
        </div>

        {/* Logistics & Practical Intel Strip */}
        <div className="bg-neutral-900 border-t border-neutral-800 p-6 grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-4 gap-6 text-xs text-neutral-300">
          <div>
            <div className="flex items-center gap-1.5 font-semibold text-neutral-200 mb-1">
              <Train className="w-3.5 h-3.5 text-amber-400" />
              <span>Recommended Transit</span>
            </div>
            <p className="text-neutral-400 leading-relaxed">
              {itinerary.logistics.transit}
            </p>
          </div>

          <div>
            <div className="flex items-center gap-1.5 font-semibold text-neutral-200 mb-1">
              <Calendar className="w-3.5 h-3.5 text-amber-400" />
              <span>Best Visiting Windows</span>
            </div>
            <p className="text-neutral-400 leading-relaxed">
              {itinerary.logistics.bestSeason}
            </p>
          </div>

          <div>
            <div className="flex items-center gap-1.5 font-semibold text-neutral-200 mb-1">
              <CreditCard className="w-3.5 h-3.5 text-amber-400" />
              <span>Est. Daily Budget</span>
            </div>
            <p className="text-neutral-400 leading-relaxed">
              {itinerary.logistics.budgetPerDay} ({itinerary.logistics.currency})
            </p>
          </div>

          <div>
            <div className="flex items-center gap-1.5 font-semibold text-neutral-200 mb-1">
              <Lightbulb className="w-3.5 h-3.5 text-amber-400" />
              <span>Local Etiquette Tip</span>
            </div>
            <p className="text-neutral-400 leading-relaxed">
              {itinerary.logistics.localTip}
            </p>
          </div>
        </div>
      </section>

      {/* Highlights Bento Row */}
      <section className="bg-white rounded-xl border border-neutral-200 p-6 shadow-sm">
        <h3 className="text-xs font-semibold uppercase tracking-wider text-neutral-500 mb-3">
          72-Hour Essential Milestones
        </h3>
        <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-4 gap-3 text-sm text-neutral-800">
          {itinerary.highlights.map((highlight, idx) => (
            <div
              key={idx}
              className="p-3 rounded-lg bg-neutral-50 border border-neutral-100 flex items-start gap-2.5"
            >
              <span className="font-mono text-xs font-bold text-neutral-400 shrink-0 mt-0.5">
                0{idx + 1}
              </span>
              <p className="text-xs text-neutral-700 leading-relaxed">
                {highlight}
              </p>
            </div>
          ))}
        </div>
      </section>

      {/* Controls Bar: Day Tabs & Category Filter */}
      <div className="space-y-4">
        <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 border-b border-neutral-200 pb-4">
          {/* Day Segmented Tabs */}
          <div className="flex items-center gap-1 p-1 bg-neutral-100 rounded-lg shrink-0">
            <button
              onClick={() => setActiveDayTab('all')}
              className={`px-3.5 py-1.5 text-xs font-semibold rounded-md transition-colors whitespace-nowrap shrink-0 ${
                activeDayTab === 'all'
                  ? 'bg-white text-neutral-900 shadow-sm'
                  : 'text-neutral-600 hover:text-neutral-900'
              }`}
            >
              All 3 Days
            </button>
            {itinerary.days.map((day) => (
              <button
                key={day.day}
                onClick={() => setActiveDayTab(day.day)}
                className={`px-3.5 py-1.5 text-xs font-semibold rounded-md transition-colors whitespace-nowrap shrink-0 ${
                  activeDayTab === day.day
                    ? 'bg-white text-neutral-900 shadow-sm'
                    : 'text-neutral-600 hover:text-neutral-900'
                }`}
              >
                Day {day.day}
              </button>
            ))}
          </div>

          {/* Category Filter Chips */}
          <div className="flex items-center gap-1.5 overflow-x-auto pb-1 sm:pb-0 scrollbar-none">
            <SlidersHorizontal className="w-3.5 h-3.5 text-neutral-400 shrink-0 mr-1" />
            {categories.map((cat) => (
              <button
                key={cat}
                onClick={() => setSelectedCategory(cat)}
                className={`px-2.5 py-1 rounded-md text-xs whitespace-nowrap shrink-0 transition-colors ${
                  selectedCategory === cat
                    ? 'bg-neutral-900 text-white font-medium'
                    : 'text-neutral-600 hover:text-neutral-900 hover:bg-neutral-100'
                }`}
              >
                {cat}
              </button>
            ))}
          </div>
        </div>
      </div>

      {/* Itinerary Schedule: Day by Day */}
      <div className="space-y-12">
        {daysToRender.map((day) => {
          const visibleActivities = filterActivities(day.activities);

          return (
            <div key={day.day} className="space-y-6">
              {/* Day Header */}
              <div className="flex flex-col md:flex-row md:items-end justify-between gap-3 border-b border-neutral-200 pb-3">
                <div>
                  <div className="flex items-center gap-2 text-xs text-neutral-500 font-medium mb-1">
                    <span className="font-mono font-bold text-neutral-800">
                      DAY 0{day.day}
                    </span>
                    <span aria-hidden="true">·</span>
                    <span>{day.theme}</span>
                  </div>
                  <h3 className="font-display text-xl sm:text-2xl font-bold text-neutral-900">
                    {day.title}
                  </h3>
                  <p className="text-sm text-neutral-600 mt-1 max-w-3xl">
                    {day.summary}
                  </p>
                </div>

                <div className="flex items-center gap-3 text-xs text-neutral-500 shrink-0 font-mono">
                  <div className="flex items-center gap-1">
                    <Footprints className="w-3.5 h-3.5 text-neutral-400" />
                    <span>{day.walkingEstimate}</span>
                  </div>
                  <span aria-hidden="true">·</span>
                  <span>{day.neighborhoods.join(', ')}</span>
                </div>
              </div>

              {/* Day Activities List */}
              {visibleActivities.length === 0 ? (
                <div className="p-8 text-center bg-white rounded-xl border border-neutral-200 text-neutral-500 text-sm">
                  No activities in Day {day.day} match the "{selectedCategory}" category filter.
                </div>
              ) : (
                <div className="space-y-4">
                  {visibleActivities.map((activity, actIdx) => {
                    const isDone = completedActivities.has(activity.id);

                    return (
                      <article
                        key={activity.id}
                        className={`rounded-xl border p-5 sm:p-6 transition-all ${
                          isDone
                            ? 'bg-neutral-50/80 border-neutral-200 opacity-75'
                            : 'bg-white border-neutral-200 shadow-sm hover:border-neutral-300'
                        }`}
                      >
                        <div className="flex items-start justify-between gap-4">
                          {/* Time & Title info */}
                          <div className="space-y-1.5 flex-1">
                            <div className="flex flex-wrap items-center gap-2 text-xs text-neutral-500">
                              <span className="font-mono tabular-nums font-semibold text-neutral-900 bg-neutral-100 px-2 py-0.5 rounded">
                                {activity.time}
                              </span>
                              <span aria-hidden="true">·</span>
                              <span className="font-medium text-neutral-700">
                                {activity.period}
                              </span>
                              <span aria-hidden="true">·</span>
                              <span>{activity.category}</span>
                              <span aria-hidden="true">·</span>
                              <span className="flex items-center gap-1 text-neutral-500">
                                <MapPin className="w-3 h-3" />
                                {activity.neighborhood}
                              </span>
                            </div>

                            <h4
                              className={`text-base sm:text-lg font-bold text-neutral-900 ${
                                isDone ? 'line-through text-neutral-500' : ''
                              }`}
                            >
                              {activity.title}
                            </h4>
                          </div>

                          {/* Completed Checklist Toggle */}
                          <button
                            type="button"
                            onClick={() => onToggleActivity(activity.id)}
                            className={`p-1.5 rounded-lg transition-colors shrink-0 focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-neutral-900 ${
                              isDone
                                ? 'text-emerald-600 bg-emerald-50 hover:bg-emerald-100'
                                : 'text-neutral-400 hover:text-neutral-700 hover:bg-neutral-100'
                            }`}
                            aria-label={
                              isDone
                                ? `Mark ${activity.title} as unvisited`
                                : `Mark ${activity.title} as visited`
                            }
                            title={isDone ? 'Mark unvisited' : 'Mark visited'}
                          >
                            {isDone ? (
                              <CheckCircle2 className="w-5 h-5 text-emerald-600" />
                            ) : (
                              <Circle className="w-5 h-5" />
                            )}
                          </button>
                        </div>

                        {/* Description */}
                        <p className="text-sm text-neutral-600 mt-2.5 leading-relaxed">
                          {activity.description}
                        </p>

                        {/* Insider Tip Callout */}
                        <div className="mt-4 p-3 rounded-lg bg-amber-50/70 border border-amber-200/60 text-xs text-amber-900 flex items-start gap-2.5">
                          <Lightbulb className="w-4 h-4 text-amber-600 shrink-0 mt-0.5" />
                          <div>
                            <span className="font-semibold text-amber-950">
                              Insider Tip:{' '}
                            </span>
                            <span>{activity.insiderTip}</span>
                          </div>
                        </div>

                        {/* Logistics Footer */}
                        <div className="mt-4 pt-3 border-t border-neutral-100 flex flex-wrap items-center justify-between text-xs text-neutral-500 gap-2">
                          <div className="flex items-center gap-3">
                            <span className="flex items-center gap-1 font-mono">
                              <Clock className="w-3 h-3 text-neutral-400" />
                              {activity.duration}
                            </span>
                            <span aria-hidden="true">·</span>
                            <span className="font-medium text-neutral-700">
                              Est. Cost: {activity.cost}
                            </span>
                          </div>

                          <span className="text-[11px] text-neutral-400">
                            Stop 0{actIdx + 1} of Day {day.day}
                          </span>
                        </div>
                      </article>
                    );
                  })}
                </div>
              )}
            </div>
          );
        })}
      </div>

      {/* 5-Item Packing List Section Below Itinerary */}
      {itinerary.packingList && itinerary.packingList.length > 0 && (
        <PackingListSection
          cityName={itinerary.name}
          items={itinerary.packingList}
        />
      )}

      {/* Switch to Other Curated Cities Footer Section */}
      <section className="mt-16 pt-10 border-t border-neutral-200">
        <div className="flex items-center justify-between mb-6">
          <div>
            <h3 className="font-display text-lg font-bold text-neutral-900">
              Explore Another Destination
            </h3>
            <p className="text-xs text-neutral-500">
              Jump to one of our other hand-crafted 3-day itineraries
            </p>
          </div>
        </div>

        <div className="grid grid-cols-1 sm:grid-cols-3 gap-4">
          {[
            { name: 'Rome', country: 'Italy', id: 'rome', img: '/src/assets/images/city_rome_colosseum_1794386868191.jpg' },
            { name: 'Paris', country: 'France', id: 'paris', img: '/src/assets/images/city_paris_rooftops_1794386868477.jpg' },
            { name: 'Tokyo', country: 'Japan', id: 'tokyo', img: '/src/assets/images/city_tokyo_street_1794386870677.jpg' },
            { name: 'New York', country: 'United States', id: 'new-york', img: '/src/assets/images/city_newyork_skyline_1794386869297.jpg' },
          ]
            .filter((c) => c.id !== itinerary.id)
            .map((city) => (
              <button
                key={city.id}
                onClick={() => onSwitchCity(city.name)}
                className="group relative h-36 rounded-xl overflow-hidden border border-neutral-200 text-left transition-transform hover:-translate-y-0.5 focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-neutral-900"
              >
                <img
                  src={city.img}
                  alt={city.name}
                  className="w-full h-full object-cover group-hover:scale-105 transition-transform duration-500"
                  referrerPolicy="no-referrer"
                />
                <div className="absolute inset-0 bg-gradient-to-t from-neutral-950/80 via-neutral-950/30 to-transparent" />
                <div className="absolute bottom-3 left-3 right-3 text-white">
                  <div className="text-[10px] uppercase tracking-wider text-neutral-300">
                    {city.country}
                  </div>
                  <div className="font-display font-bold text-base flex items-center justify-between">
                    <span>{city.name}</span>
                    <ChevronRight className="w-4 h-4 text-neutral-300 group-hover:translate-x-1 transition-transform" />
                  </div>
                </div>
              </button>
            ))}
        </div>
      </section>
    </div>
  );
};
